export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? ""));
}

export function formatDuration(seconds: number, copy: Copy, locale: Locale): string {
  if (seconds <= 0) return `0 ${copy.units.s}`;
  if (seconds < 60) return `${seconds} ${copy.units.s}`;
  if (seconds < 3600) {
    const m = Math.floor(seconds / 60);
    const s = seconds % 60;
    return s ? `${m} ${copy.units.min} ${s} ${copy.units.s}` : `${m} ${copy.units.min}`;
  }
  const hours = seconds / 3600;
  const comma = locale === "ru" || locale === "de" || locale === "it" || locale === "es";
  const text = hours >= 10 ? String(Math.round(hours)) : hours.toFixed(1).replace(".", comma ? "," : ".");
  return `${text} ${copy.units.h}`;
}

